        WHEN cp.latest_order_date IS NULL
            THEN NULL

        ELSE
            DATEDIFF(
                DAY,
                CAST(
                    cp.latest_order_date
                    AS DATE
                ),
                @analysis_date
            )
    END AS recency,

    COALESCE(
        cp.frequency,
        0
    ) AS frequency,

    COALESCE(
        cp.monetary,
        0
    ) AS monetary,

    CASE
        WHEN cp.customer_id IS NULL
            THEN 'No Completed Purchases'
        ELSE 'RFM Eligible'
    END AS rfm_population

FROM training.customers AS c

LEFT JOIN CustomerPurchases AS cp
    ON c.customer_id = cp.customer_id

ORDER BY monetary DESC;
GO


