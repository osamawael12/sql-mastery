/* ==========================================================
   FINAL BUSINESS DEFINITIONS

   RFM ELIGIBLE CUSTOMER:

       Customer with at least one Completed order.


   RECENCY:

       Analysis Date
       -
       Latest Completed Order Date

       Lower is better.


   FREQUENCY:

       Number of distinct Completed orders.

       Higher is better.


   MONETARY:

       Completed revenue generated by customer.

       Higher is better.


   ANALYSIS DATE:

       One day after maximum Completed order date.

       This makes historical analysis reproducible.


   SCORING:

       This training implementation uses NTILE(5).

       Higher scores are designed to mean better
       customer behavior.


   IMPORTANT LIMITATIONS:

   1. NTILE creates row-count buckets,
      not equal business-value ranges.

   2. Tiny datasets may not fill all 5 scores.

   3. Ties can be split across NTILE buckets.

   4. RFM segment rules are business decisions.

   5. Customers without Completed purchases should
      generally be handled outside purchase-based RFM.

   6. Do not use GETDATE() blindly for historical
      RFM analysis.

   7. Validate:

      SUM(Frequency)
          =
      Completed Order Count

      SUM(Monetary)
          =
      Completed Revenue

============================================================
END OF RFM ANALYSIS
============================================================
*/