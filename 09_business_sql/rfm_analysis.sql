/* ==========================================================
   13. RFM SCORING WITH NTILE

   Score range used here:

   1 to 5

   Higher score = better.

   Therefore:

   Recency:
       lower recency should receive higher score.

   Frequency:
       higher frequency should receive higher score.

   Monetary:
       higher monetary should receive higher score.

   IMPORTANT:

   The training dataset may contain fewer than
   five purchasing customers.

   NTILE(5) will therefore not produce all five
   score values in a tiny dataset.
   ========================================================== */

DECLARE @analysis_date DATE;

SELECT
    @analysis_date =
        DATEADD(
            DAY,
            1,
            CAST(
                MAX(order_date)
                AS DATE
            )
        )
FROM training.orders
WHERE order_status = 'Completed';


;WITH CompletedSales AS
(
    SELECT
        o.order_id,
        o.customer_id,
        o.order_date,

        oi.quantity * oi.unit_price
            AS line_revenue

    FROM training.orders AS o

    INNER JOIN training.order_items AS oi
        ON o.order_id = oi.order_id

    WHERE o.order_status = 'Completed'
),
CustomerRFM AS
(
    SELECT
        customer_id,

        DATEDIFF(
            DAY,
            CAST(
                MAX(order_date)
                AS DATE
            ),
            @analysis_date
        ) AS recency,

        COUNT(DISTINCT order_id)
            AS frequency,

        SUM(line_revenue)
            AS monetary

    FROM CompletedSales

    GROUP BY customer_id
),
RFMScores AS
(
    SELECT
        customer_id,
        recency,
        frequency,
        monetary,

        NTILE(5) OVER
        (
            ORDER BY
                recency DESC,
                customer_id
        ) AS r_score,

        NTILE(5) OVER
        (
            ORDER BY
                frequency ASC,
                customer_id
        ) AS f_score,

        NTILE(5) OVER
        (
            ORDER BY
                monetary ASC,
                customer_id
        ) AS m_score

    FROM CustomerRFM
)
SELECT
    customer_id,
    recency,
    frequency,
    monetary,
    r_score,
    f_score,
    m_score

FROM RFMScores

ORDER BY
    r_score DESC,
    f_score DESC,
    m_score DESC;
GO


/* ==========================================================
   14. WHY RECENCY ORDER IS REVERSED

   NTILE assigns bucket 1 to the first ordered rows
   and higher bucket values later.

   We want:

   most recent customer
       -> highest R score

   Therefore we order recency DESC.

   Example concept:

   high recency days (worse)
       appears first
       -> low score

   low recency days (better)
       appears later
       -> high score
   ========================================================== */


