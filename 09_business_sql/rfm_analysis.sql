   Classical RFM is usually built on customers
   with purchase history.

   But a full customer report may also need customers
   without Completed orders.

   For these customers:

   Frequency = 0
   Monetary = 0
   Recency = NULL

   They should normally be handled separately instead
   of forcing them into purchase-based RFM scoring.
   ========================================================== */

