/*
============================================================
SQL MASTERY
09 - BUSINESS SQL

File: rfm_analysis.sql
Database: SQLMastery
Language: T-SQL

RFM =
Recency
Frequency
Monetary

Business Definitions:

Recency:
    Number of days since customer's latest
    Completed order.

Frequency:
    Number of distinct Completed orders.

Monetary:
    Completed revenue generated by the customer.

Revenue:
    SUM(quantity * unit_price)

Reference Date:
    One day after the latest Completed order date
    in the dataset.

This makes the analysis reproducible for the
historical training dataset.

Important:
RFM scoring and segment definitions are business rules.
There is no universal scoring model.
============================================================
*/

USE SQLMastery;
GO


/* ==========================================================
   1. LATEST COMPLETED ORDER IN DATASET

   Before calculating Recency, understand the
   latest date represented in the data.
   ========================================================== */

SELECT
    MAX(order_date)
        AS latest_completed_order_datetime

FROM training.orders

WHERE order_status = 'Completed';
GO


/* ==========================================================
   2. ANALYSIS DATE

   Use:

   one day after the latest Completed order.

   This avoids using GETDATE(), which would cause
   historical RFM values to change over time.
   ========================================================== */

SELECT
    DATEADD(
        DAY,
        1,
        CAST(
            MAX(order_date)
            AS DATE
        )
    ) AS analysis_date

FROM training.orders

WHERE order_status = 'Completed';
GO


/* ==========================================================
   3. STORE ANALYSIS DATE IN A VARIABLE

   This reference date is reused in several queries.
   ========================================================== */

DECLARE @analysis_date DATE;

SELECT
    @analysis_date =
        DATEADD(
            DAY,
            1,
            CAST(
                MAX(order_date)
                AS DATE
            )
        )
FROM training.orders
WHERE order_status = 'Completed';

SELECT
    @analysis_date AS analysis_date;
GO


/* ==========================================================
   4. RECENCY FOUNDATION

   Latest Completed order for each purchasing customer.
   ========================================================== */

SELECT
    o.customer_id,

    MAX(o.order_date)
        AS latest_completed_order

FROM training.orders AS o

WHERE o.order_status = 'Completed'

GROUP BY o.customer_id

ORDER BY latest_completed_order DESC;
GO


/* ==========================================================
   5. RECENCY

   Recency =
   days between latest Completed order
   and analysis date.

   Smaller is better.
   ========================================================== */

DECLARE @analysis_date DATE;

SELECT
    @analysis_date =
        DATEADD(
            DAY,
            1,
            CAST(
                MAX(order_date)
                AS DATE
            )
        )
FROM training.orders
WHERE order_status = 'Completed';


SELECT
    o.customer_id,

    MAX(o.order_date)
        AS latest_completed_order,

    DATEDIFF(
        DAY,
        CAST(
            MAX(o.order_date)
            AS DATE
        ),
        @analysis_date
    ) AS recency_days

FROM training.orders AS o

WHERE o.order_status = 'Completed'

GROUP BY o.customer_id

ORDER BY recency_days;
GO


/* ==========================================================
   6. FREQUENCY

   Frequency =
   number of Completed orders.

   Starting from orders means one source row
   represents one order.
   ========================================================== */

SELECT
    customer_id,

    COUNT(*) AS frequency

FROM training.orders

WHERE order_status = 'Completed'

GROUP BY customer_id

ORDER BY frequency DESC;
GO


/* ==========================================================
   7. MONETARY

   Monetary =
   Completed customer revenue.
   ========================================================== */

SELECT
    o.customer_id,

    SUM(
        oi.quantity * oi.unit_price
    ) AS monetary

FROM training.orders AS o

INNER JOIN training.order_items AS oi
    ON o.order_id = oi.order_id

WHERE o.order_status = 'Completed'

GROUP BY o.customer_id

ORDER BY monetary DESC;
GO


/* ==========================================================
   8. BASIC RFM TABLE

   One row per customer who has at least one
   Completed order.

   Metrics:

   Recency
   Frequency
   Monetary
   ========================================================== */

DECLARE @analysis_date DATE;

SELECT
    @analysis_date =
        DATEADD(
            DAY,
            1,
            CAST(
                MAX(order_date)
                AS DATE
            )
        )
FROM training.orders
WHERE order_status = 'Completed';


;WITH CustomerOrders AS
(
    SELECT
        customer_id,

        MAX(order_date)
            AS latest_completed_order,

        COUNT(*)
            AS frequency

    FROM training.orders

    WHERE order_status = 'Completed'

    GROUP BY customer_id
),
CustomerMonetary AS
(
    SELECT
        o.customer_id,

        SUM(
            oi.quantity * oi.unit_price
        ) AS monetary

    FROM training.orders AS o

    INNER JOIN training.order_items AS oi
        ON o.order_id = oi.order_id

    WHERE o.order_status = 'Completed'

    GROUP BY o.customer_id
)
SELECT
    c.customer_id,
    c.customer_name,

    @analysis_date
        AS analysis_date,

    co.latest_completed_order,

    DATEDIFF(
        DAY,
        CAST(
            co.latest_completed_order
            AS DATE
        ),
        @analysis_date
    ) AS recency_days,

    co.frequency,
    cm.monetary

FROM CustomerOrders AS co

INNER JOIN CustomerMonetary AS cm
    ON co.customer_id = cm.customer_id

INNER JOIN training.customers AS c
    ON co.customer_id = c.customer_id

ORDER BY cm.monetary DESC;
GO


